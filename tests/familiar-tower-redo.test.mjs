 const raw=JSON.parse(load('6b13d1a-genuine40')),s=decode(load('6b13d1a-genuine40'));
 assert.equal(raw.familiarTower.policyVersion,2);assert.equal(raw.familiarTower.legacy,undefined);
 assert.deepEqual(s.familiarTower,{...raw.familiarTower,policyVersion:3,base:0});
 assert.equal(s.familiarTower.last.combatVersion,10);assert.ok(valid(s));
 // Live-build figures, printed by 6b13d1a for this save.
 assert.deepEqual(towerIncome(s),{levelUp:116,classUp:4});assert.deepEqual(suppliesWaiting(s),{levelUp:232,classUp:8,hours:2});
 assert.deepEqual(familiarSupplies(s),raw.familiarSupplies,'nothing settled: the floor did not change');
