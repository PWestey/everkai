test('NEGATIVE CONTROL: the reset cannot be forged or skipped',()=>{
 const s=decode(load('bafe728-floor7')),t=s.familiarTower;
 const bad=(x,why)=>assert.equal(validTower({...s,familiarTower:x}),false,why);
 bad({...t,cleared:175},'claiming the old floor without reports');
 bad({...t,base:t.attempts+1},'a base above attempts');
 bad({...t,redoFrom:301},'a reach past the top');
 bad({...t,prepaid:{from:1,to:300}},'prepaid floors beyond the reach');
 bad({...t,policyVersion:2},'a policy-2 record without its 25n floor');
 bad({...t,legacy:{...t.legacy,cleared:12}},'a legacy record that does not replay');
 bad({...t,extra:1},'an unknown key');
 // migrateTower is exact.
 assert.deepEqual(migrateTower({policyVersion:1,cleared:3,attempts:5,party:['a'],last:{x:1}}),{policyVersion:3,cleared:0,attempts:5,base:5,party:['a'],last:null,legacy:{cleared:3,attempts:5,last:{x:1}},redoFrom:75});
 assert.deepEqual(migrateTower({policyVersion:2,cleared:80,attempts:9,party:[],last:{y:1},legacy:{cleared:3,attempts:5,last:null}}),{policyVersion:3,cleared:0,attempts:9,base:9,party:[],last:null,legacy:{cleared:3,attempts:5,last:null},redoFrom:80,prepaid:{from:76,to:80}});
 const p3={policyVersion:3,cleared:4,attempts:4,base:0,party:[],last:null};assert.equal(migrateTower(p3),p3);
 assert.equal(floorRewardItems(1).length,1);
});
