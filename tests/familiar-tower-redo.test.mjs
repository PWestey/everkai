// The owner, 2026-09-16: "Re-do floor since I don't ever remember actually doing them." Sandbox-era towers restart
// the 300 floors at 0 (lib/familiar-tower.mjs policy 3). CLAUDE.md rule 12: every fixture below was GENERATED by an
// older build, never written by hand, and every "OLD" figure was printed by that build from the same save:
//  * familiar-save-bafe728-floor{7,12}.json  -- the 12-floor sandbox build (scripts/generate-legacy-familiar-saves.mjs)
//  * familiar-save-6b13d1a-*.json            -- the LIVE 25n build, which the owner's save has probably loaded
//                                               (scripts/generate-live-familiar-saves.mjs)
const H=3600e3;
const load=name=>readFileSync(new URL(`./familiar-save-${name}.json`,import.meta.url),'utf8');
const OLD={
 'bafe728-floor7':{waiting:{levelUp:688,classUp:28},unlocked:[true,true,true,true,true,true,false,false,false],reach:175},
 'bafe728-floor12':{waiting:{levelUp:748,classUp:32},unlocked:[true,true,true,true,true,true,true,true,true],reach:300},
 '6b13d1a-climbed180':{waiting:{levelUp:522,classUp:21},unlocked:[true,true,true,true,true,true,false,false,false],reach:180,area:2,prepaid:{from:176,to:180}},
 '6b13d1a-floor300':{waiting:{levelUp:748,classUp:32},unlocked:[true,true,true,true,true,true,true,true,true],reach:300},
};

for(const [name,old] of Object.entries(OLD))test(`${name}: resets to floor 0 once, keeps every item already earned, and loses no unlock`,()=>{
 const raw=JSON.parse(load(name)),s=decode(load(name)),t=s.familiarTower;
 assert.ok([1,2].includes(raw.familiarTower.policyVersion),'fixture is an old policy');
 if(raw.familiarTower.policyVersion===2)assert.ok(raw.familiarTower.legacy,'fixture is a live-migrated sandbox save');
 assert.ok(valid(s));
 assert.equal(t.policyVersion,3);assert.equal(t.cleared,0);assert.equal(t.last,null);
 assert.equal(t.base,raw.familiarTower.attempts);assert.equal(t.attempts,raw.familiarTower.attempts);assert.deepEqual(t.party,raw.familiarTower.party);
 assert.equal(t.redoFrom,old.reach);assert.deepEqual(t.prepaid,old.prepaid);
 // NO LOSS: the income that was waiting at the old floor's rate is settled into the store on load.
 const f=familiarSupplies(s),rf=raw.familiarSupplies;
 assert.deepEqual({levelUp:f.levelUp-rf.levelUp,classUp:f.classUp-rf.classUp},old.waiting,'waiting income banked at the old rate');
 assert.deepEqual(suppliesWaiting(s),{levelUp:0,classUp:0,hours:0},'and not waiting a second time');
 assert.deepEqual(towerIncome(s),{levelUp:0,classUp:0},'the hourly rate is that of the floor actually climbed: none yet');
 // NO LOST ACCESS: dispatch and exploring areas unlock from the floor reached before the redo.
 assert.equal(towerReachOf(s),old.reach);
 assert.deepEqual(DISPATCH_AREAS.map(a=>dispatchUnlocked(s,a.id)),old.unlocked);
 assert.deepEqual(dispatchState(s),raw.familiarDispatch,'the run already out is untouched');assert.ok(validFamiliarDispatch(s));
 if(old.area){assert.equal(exploreState(s).area,old.area);assert.ok(validFamiliarExplore(s));}
 // NO CLAWBACK: familiars, pearls, EXP.
 assert.deepEqual(s.familiars,raw.familiars);assert.equal(s.fellowXP,raw.fellowXP);assert.equal(s.inventory.Item_Talent_Hero_1,raw.inventory.Item_Talent_Hero_1);
 // EXACTLY ONCE: loading the reset save again changes nothing.
 assert.deepEqual(decode(JSON.stringify(s)),s);
 // The run out is still collectable when it is done.
 if(raw.familiarDispatch.run){const back=act(s,'dispatchCollect',raw.familiarDispatch.run.since+20*H);assert.equal(back.error,undefined);assert.equal(dispatchState(back.state).run,null);assert.ok(valid(back.state));}
});

