// Writes lib/art-bounds-data.json: where the character art sits inside every portrait still and idle
// clip the app shows (see scripts/measure-art-bounds.swift for the method). macOS only: it compiles the
// Swift measurer with swiftc and reads WebP/H.264 through ImageIO and AVFoundation.
//   node scripts/measure-art-bounds.mjs
import {execFileSync} from 'node:child_process';
import {mkdtempSync,writeFileSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {FELLOWS,FAMILY} from '../lib/catalog.mjs';
import costumes from '../lib/wardrobe-assets.json' with {type:'json'};
import clips from '../lib/character-idle-data.json' with {type:'json'};
import {installedCrossoverAssets} from './crossover/installed-assets.mjs';

const root=new URL('..',import.meta.url).pathname,assets=join(root,'public/assets');
// installedCrossoverAssets() is added UNCONDITIONALLY: FELLOWS/FAMILY are flag-gated and Node never
// has the flag, so without it no crossover render is ever measured and every one of them loses its
// framing transform. Art bounds are a static property of a file, not of a feature flag.
const paths=[...new Set([...[...FELLOWS,...FAMILY].flatMap(f=>[f.art,f.portrait]),...costumes.map(c=>c.art),...Object.values(clips).map(c=>c.src),...installedCrossoverAssets()].filter(Boolean))].sort();
const bin=join(mkdtempSync(join(tmpdir(),'art-bounds-')),'measure');
execFileSync('swiftc',['-O','-suppress-warnings',join(root,'scripts/measure-art-bounds.swift'),'-o',bin],{stdio:'inherit'});
const rows=[];
for(let i=0;i<paths.length;i+=40){
 const out=execFileSync(bin,[assets,...paths.slice(i,i+40)],{maxBuffer:1<<26}).toString().trim().split('\n').map(line=>JSON.parse(line));
 rows.push(...out);process.stderr.write(`\r${rows.length}/${paths.length}`);
}
process.stderr.write('\n');
const failed=rows.filter(r=>r.error);if(failed.length)throw Error('Unreadable: '+failed.map(r=>r.path).join(', '));
// Only a measured surround is stored; an asset absent from the table fills its frame.
const data={};
for(const r of rows){
 const entry={};
 if(r.surround)Object.assign(entry,{bounds:r.bounds,surround:r.surround});
 if(r.motion!==null)entry.motion=r.motion;
 if(Object.keys(entry).length)data[r.path]=entry;
}
writeFileSync(join(root,'lib/art-bounds-data.json'),JSON.stringify({
 note:'Generated by scripts/measure-art-bounds.mjs. bounds = [x0,y0,x1,y1] of the art as fractions of the 2:3 frame, measured against a flat viewer surround (surround = its colour); assets without bounds fill their frame. motion = fraction of pixels that change across 24 sampled clip frames; 0 means a frozen clip.',
 measured:paths.length,
 assets:data
},null,1)+'\n');
console.log(`measured ${paths.length} assets, ${Object.values(data).filter(r=>r.bounds).length} with a flat surround`);
